import { TestBed } from '@angular/core/testing';
import { App } from './app';

describe('App', () => {
  beforeEach(async () => {
    await TestBed.configureTestingModule({
      imports: [App],
    })
      .compileComponents();
  });

  it('should create the app', () => {
    const fixture = TestBed.createComponent(App);
    const app = fixture.componentInstance;
    expect(app).toBeTruthy();
  });

  it('should provide administrator-created account sign-in without public registration', async () => {
    const fixture = TestBed.createComponent(App);
    await fixture.whenStable();
    const compiled = fixture.nativeElement as HTMLElement;
    expect(compiled.querySelector('h1')?.textContent).toContain('Every journey');
    expect(compiled.querySelector('input[autocomplete="username"]')).toBeTruthy();
    expect(compiled.textContent?.toLowerCase()).not.toContain('sign up');
    expect(compiled.textContent?.toLowerCase()).not.toContain('register');
  });
});
